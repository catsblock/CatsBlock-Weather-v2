package com.catsblock.weather.i18n

fun trx(en: String): String {
    val l = I18n.lang
    if (l == AppLanguage.English) return en
    return X[en]?.getOrNull(l.ordinal - 1) ?: extra(en) ?: en
}

fun leadFull(minutes: Int): String = trx(
    when (minutes) {
        1440 -> "24 hours"
        720 -> "12 hours"
        360 -> "6 hours"
        180 -> "3 hours"
        120 -> "2 hours"
        60 -> "1 hour"
        30 -> "30 minutes"
        else -> "15 minutes"
    }
)

